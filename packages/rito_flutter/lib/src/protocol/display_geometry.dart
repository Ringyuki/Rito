final class RitoDisplayPoint {
  const RitoDisplayPoint({required this.x, required this.y});

  final double x;
  final double y;
}

final class RitoDisplayRect {
  const RitoDisplayRect({
    required this.x,
    required this.y,
    required this.width,
    required this.height,
  });

  final double x;
  final double y;
  final double width;
  final double height;
}
